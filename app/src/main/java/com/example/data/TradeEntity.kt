package com.example.data

import androidx.room.Entity
import androidx.room.PrimaryKey
import com.example.model.Trade
import com.example.model.TradeDirection
import com.example.model.TradeVisibility

@Entity(tableName = "trades")
data class TradeEntity(
    @PrimaryKey(autoGenerate = true)
    val id: Long = 0,
    val pair: String,
    val direction: String,
    val setupStrategy: String,
    val session: String,
    val timeframe: String,
    val entryPrice: Double,
    val stopLoss: Double,
    val takeProfit: Double,
    val exitPrice: Double?,
    val positionSizeLots: Double,
    val riskRewardRatio: String,
    val rMultiple: Double,
    val netGainDollars: Double,
    val riskPercent: Double,
    val maxRiskDollars: Double,
    val visibility: String,
    val publicPostAudience: String = "everyone",
    val winRatePercent: Double? = null,
    val status: String = "WINNER",
    val timestamp: Long,
    val timeAgo: String,
    val authorName: String,
    val authorHandle: String,
    val authorTier: String = "VERIFIED",
    val isAuthorVerified: Boolean,
    val executionThesis: String,
    val psychologyNote: String?,
    val postMortemReflection: String?,
    val planAdherencePercent: Int,
    val disciplineScore: Double,
    val tagsString: String,
    val chartDrawableRes: Int?,
    val chartImageUri: String?,
    val chartOverlayText: String?,
    val tapeSpeed: String?,
    val upvotes: Int,
    val downvotes: Int,
    val commentsCount: Int,
    val isUpvoted: Boolean,
    val isDownvoted: Boolean,
    val isBookmarked: Boolean,
    val brokerName: String,
    val slippagePips: Double,
    val durationText: String
) {
    fun toDomain(): Trade = Trade(
        id = id,
        pair = pair,
        direction = if (direction == "SHORT") TradeDirection.SHORT else TradeDirection.LONG,
        setupStrategy = setupStrategy,
        session = session,
        timeframe = timeframe,
        entryPrice = entryPrice,
        stopLoss = stopLoss,
        takeProfit = takeProfit,
        exitPrice = exitPrice,
        positionSizeLots = positionSizeLots,
        riskRewardRatio = riskRewardRatio,
        rMultiple = rMultiple,
        netGainDollars = netGainDollars,
        riskPercent = riskPercent,
        maxRiskDollars = maxRiskDollars,
        visibility = if (visibility == "PRIVATE") TradeVisibility.PRIVATE else TradeVisibility.PUBLIC,
        publicPostAudience = publicPostAudience,
        winRatePercent = winRatePercent,
        status = when (status) {
            "OPEN" -> com.example.model.TradeStatus.OPEN
            "STOPPED" -> com.example.model.TradeStatus.STOPPED
            "BREAKEVEN" -> com.example.model.TradeStatus.BREAKEVEN
            "CANCELLED" -> com.example.model.TradeStatus.CANCELLED
            else -> com.example.model.TradeStatus.WINNER
        },
        timestamp = timestamp,
        timeAgo = timeAgo,
        authorName = authorName,
        authorHandle = authorHandle,
        authorTier = try { com.example.model.TraderTier.valueOf(authorTier) } catch (e: Exception) { com.example.model.TraderTier.VERIFIED },
        isAuthorVerified = isAuthorVerified,
        executionThesis = executionThesis,
        psychologyNote = psychologyNote,
        postMortemReflection = postMortemReflection,
        planAdherencePercent = planAdherencePercent,
        disciplineScore = disciplineScore,
        tags = if (tagsString.isBlank()) emptyList() else tagsString.split(",").map { it.trim() },
        chartDrawableRes = chartDrawableRes,
        chartImageUri = chartImageUri,
        chartOverlayText = chartOverlayText,
        tapeSpeed = tapeSpeed,
        upvotes = upvotes,
        downvotes = downvotes,
        commentsCount = commentsCount,
        isUpvoted = isUpvoted,
        isDownvoted = isDownvoted,
        isBookmarked = isBookmarked,
        brokerName = brokerName,
        slippagePips = slippagePips,
        durationText = durationText
    )

    companion object {
        fun fromDomain(trade: Trade): TradeEntity = TradeEntity(
            id = trade.id,
            pair = trade.pair,
            direction = trade.direction.name,
            setupStrategy = trade.setupStrategy,
            session = trade.session,
            timeframe = trade.timeframe,
            entryPrice = trade.entryPrice,
            stopLoss = trade.stopLoss,
            takeProfit = trade.takeProfit,
            exitPrice = trade.exitPrice,
            positionSizeLots = trade.positionSizeLots,
            riskRewardRatio = trade.riskRewardRatio,
            rMultiple = trade.rMultiple,
            netGainDollars = trade.netGainDollars,
            riskPercent = trade.riskPercent,
            maxRiskDollars = trade.maxRiskDollars,
            visibility = trade.visibility.name,
            publicPostAudience = trade.publicPostAudience,
            winRatePercent = trade.winRatePercent,
            status = trade.status.name,
            timestamp = trade.timestamp,
            timeAgo = trade.timeAgo,
            authorName = trade.authorName,
            authorHandle = trade.authorHandle,
            authorTier = trade.authorTier.name,
            isAuthorVerified = trade.isAuthorVerified,
            executionThesis = trade.executionThesis,
            psychologyNote = trade.psychologyNote,
            postMortemReflection = trade.postMortemReflection,
            planAdherencePercent = trade.planAdherencePercent,
            disciplineScore = trade.disciplineScore,
            tagsString = trade.tags.joinToString(","),
            chartDrawableRes = trade.chartDrawableRes,
            chartImageUri = trade.chartImageUri,
            chartOverlayText = trade.chartOverlayText,
            tapeSpeed = trade.tapeSpeed,
            upvotes = trade.upvotes,
            downvotes = trade.downvotes,
            commentsCount = trade.commentsCount,
            isUpvoted = trade.isUpvoted,
            isDownvoted = trade.isDownvoted,
            isBookmarked = trade.isBookmarked,
            brokerName = trade.brokerName,
            slippagePips = trade.slippagePips,
            durationText = trade.durationText
        )
    }
}
